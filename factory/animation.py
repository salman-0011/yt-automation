"""2.5D cartoon animation scaffolding — Motion Canvas + Manim (CPU).

This does NOT render animation itself (that needs Node/Manim installed).
It writes a ready-to-run project skeleton for a job, so the user edits
one file per scene instead of starting from zero. Blender is NOT a core
tool here: it will not run well on the Toshiba A30-D (2-core, no GPU).
Maps are built from verified base data and animated in CapCut — never
ask an AI model for accurate geography.
"""
from __future__ import annotations

from pathlib import Path

MOTION_CANVAS_SCENE = """// Motion Canvas scene — generated by factory/animation.py
// Run: npm install && npm run serve   (see jobs/<job>/animation/README.md)
import {makeScene2D, Circle, Rect, Txt} from '@motion-canvas/2d';
import {createRef, waitFor} from '@motion-canvas/core';

export default makeScene2D(function* (view) {
  const title = createRef<Txt>();
  view.add(<Txt ref={title} fontSize={72} fill={'#ffffff'}>{TITLE}</Txt>);
  yield* waitFor(2);
  // TODO: add one subject, one camera move, one action per scene.
  // Keep every visual explaining the narration — never decoration only.
});
"""

MANIM_SCENE = '''"""Manim scene — generated by factory/animation.py
Run (720p, CPU): manim render -qm --format=mp4 scene.py {ClassName}
Keep 720p on this laptop; 1080p is slow and rarely needed for a draft.
"""
from manim import *

class {ClassName}(Scene):
    def construct(self):
        title = Text("{title}", font_size=36)
        self.play(Write(title))
        self.wait(1)
        # TODO: one mechanism per scene — e.g. arrows showing flow/force.
        # Use 2.5D cartoon colours: bright fills, big arrows, large banners.
'''


def scaffold_animation(job_dir: Path, title: str, kind: str = "long") -> Path:
    """Write animation/ skeleton (Motion Canvas + Manim). Returns the dir."""
    base = Path(job_dir) / "animation"
    (base / "motion-canvas" / "src" / "scenes").mkdir(parents=True, exist_ok=True)
    (base / "manim").mkdir(parents=True, exist_ok=True)
    (base / "motion-canvas" / "src" / "scenes" / "scene-01.tsx").write_text(
        MOTION_CANVAS_SCENE.replace("{TITLE}", title), encoding="utf-8")
    (base / "manim" / "scene.py").write_text(
        MANIM_SCENE.replace("{ClassName}", "Scene01").replace("{title}", title),
        encoding="utf-8")
    (base / "README.md").write_text(
        "# Animation (2.5D cartoon)\n\n"
        "Motion Canvas (TypeScript, best for map/diagram motion):\n"
        "  cd animation/motion-canvas && npm install && npm run serve\n"
        "Manim (Python, best for mechanisms/math):\n"
        "  cd animation/manim && manim render -qm --format=mp4 scene.py Scene01\n"
        "Rules: one subject, one camera move, one action per scene. "
        "Maps only from verified base data. All text/labels in CapCut, "
        "never generated inside the animation.\n",
        encoding="utf-8")
    return base
