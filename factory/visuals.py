"""Pluggable video backends — the supervisor picks, Python renders.

  stills        — ONE real still per scene (jobs/<job>/stills/scene-NN.jpg,
                  generated by hand in Nano Banana from
                  prompts/stills-prompts.md), slow Ken Burns pan/zoom per
                  scene via FFmpeg zoompan. THE default auto backend.
                  If a still is missing, the job FAILS with the exact
                  filename + prompt — it never renders a substitute.
  motion-canvas — Motion Canvas project per scene; rendered with Node.
                  No fallback: if Node / the render fails, the job stops
                  with a clear error.
  manim         — Manim scene per scene, 720p. No fallback: if Manim is
                  not installed or the render fails, the job stops.
  flow-manual   — NOT a render backend. Flow has no public API; the job
                  folder keeps Flow prompts for the human. Auto-run with
                  this backend stops with a clear message.

DELETED in v2.3: the "code" backend (Pillow solid-colour scene cards
with the whole narration burned on as big text plus a "Scene N •
style" debug label). It produced the 40-second Constantinople test
video rated 2/10: coloured cards, no ships, two overlapping text
layers. No backend in this file may ever burn scene text, a scene
number, or a style label into a clip, and no backend may fall back
to a text card. Every backend returns scene mp4s in
jobs/<job>/clips/auto-scene-NN.mp4 plus a log of which backend
actually rendered each scene. Nothing here pretends a manual step
happened.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from .options import JobOptions
from .stills import write_stills_guide


def _kenburns_clip(still: Path, out: Path, duration: float,
                   width: int, height: int, variant: int) -> bool:
    """One real still -> one moving clip (slow Ken Burns, never static).

    Variants alternate per scene: 0 zoom-in, 1 zoom-out, 2 pan-right,
    3 pan-left. The still is first scaled/cropped (cover) to 2x the
    target size so the zoom/pan never exposes an edge or upscales.
    """
    frames = max(24, int(duration * 24))
    sw, sh = width * 2, height * 2
    if variant == 0:      # slow zoom in
        z = "min(1+0.0012*on,1.20)"
        x = "iw/2-(iw/zoom/2)"
        y = "ih/2-(ih/zoom/2)"
    elif variant == 1:    # slow zoom out
        z = "max(1.20-0.0012*on,1.00)"
        x = "iw/2-(iw/zoom/2)"
        y = "ih/2-(ih/zoom/2)"
    elif variant == 2:    # slow pan right
        z = "1.20"
        x = f"(iw-iw/zoom)*on/{frames - 1}"
        y = "ih/2-(ih/zoom/2)"
    else:                 # slow pan left
        z = "1.20"
        x = f"(iw-iw/zoom)*(1-on/{frames - 1})"
        y = "ih/2-(ih/zoom/2)"
    filt = (f"scale={sw}:{sh}:force_original_aspect_ratio=increase,"
            f"crop={sw}:{sh},"
            f"zoompan=z='{z}':x='{x}':y='{y}':d={frames}:s={width}x{height}:fps=24,"
            f"format=yuv420p")
    try:
        r = subprocess.run(["ffmpeg", "-y", "-loop", "1", "-i", str(still),
                            "-vf", filt, "-t", str(duration),
                            "-c:v", "libx264", "-preset", "veryfast",
                            "-pix_fmt", "yuv420p", str(out)],
                           capture_output=True, text=True, timeout=600)
        return r.returncode == 0 and out.exists() and out.stat().st_size > 0
    except Exception:
        return False


def render_stills(job_dir: Path, scenes: list[dict],
                  options: JobOptions, angle: dict | None = None
                  ) -> tuple[list[Path], str]:
    """Real-stills backend. Returns (scene clips, log line).

    Fails (empty clips + a message naming every missing still) rather
    than rendering any substitute. The message is the _StepFail text
    the runner shows the user.
    """
    from .stills import find_still
    job_dir = Path(job_dir)
    guide, check = write_stills_guide(job_dir, scenes, options, angle)
    if check["missing"]:
        names = ", ".join(m["filename"] for m in check["missing"])
        return [], (f"stills backend stopped: {len(check['missing'])} of "
                    f"{check['expected']} scene stills are missing "
                    f"({names}). Generate them in Nano Banana from "
                    f"prompts/stills-prompts.md, save each one as "
                    f"jobs/<slug>/stills/<filename>, then press Run again "
                    f"(it resumes from the visuals step). No coloured card "
                    f"was rendered as a substitute.")
    clips_dir = job_dir / "clips"
    clips_dir.mkdir(parents=True, exist_ok=True)
    clips: list[Path] = []
    for i, scene in enumerate(scenes):
        still = find_still(job_dir, i)
        assert still is not None  # checked above; kept for type-checkers
        clip = clips_dir / f"auto-scene-{i + 1:02d}.mp4"
        if not _kenburns_clip(still, clip, float(scene["duration"]),
                              options.width, options.height, i % 4):
            return clips, (f"stills backend failed: FFmpeg Ken Burns failed "
                           f"on scene {i + 1} ({still.name})")
        clips.append(clip)
    return clips, (f"stills backend rendered {len(clips)} scene clips "
                   f"from real stills in jobs/<job>/stills/ "
                   f"(Ken Burns pan/zoom, no burned-in text)")


def render_motion_canvas(job_dir: Path, scenes: list[dict],
                         options: JobOptions) -> tuple[list[Path], str]:
    """Try Motion Canvas. NO fallback to text cards on any failure."""
    if shutil.which("node") is None or shutil.which("npx") is None:
        return [], ("motion-canvas not available (no Node/npx on this machine) — "
                    "install Node, or pick the stills backend. No text-card "
                    "fallback is rendered.")
    base = Path(job_dir) / "animation" / "motion-canvas"
    scene_dir = base / "src" / "scenes"
    scene_dir.mkdir(parents=True, exist_ok=True)
    for i, scene in enumerate(scenes):
        (scene_dir / f"scene-{i + 1:02d}.tsx").write_text(
            "// Motion Canvas scene — render with: npm install && npx @motion-canvas/cli render\n"
            "// One subject, one camera move, one action per scene. No text in the animation.\n"
            "import {makeScene2D} from '@motion-canvas/2d';\n"
            "import {waitFor} from '@motion-canvas/core';\n"
            f"// Scene {i + 1}: {str(scene.get('narration', ''))[:80]}\n"
            "export default makeScene2D(function* (view) {\n"
            f"  yield* waitFor({scene['duration']});\n}});\n", encoding="utf-8")
    try:
        r = subprocess.run(["npx", "@motion-canvas/cli", "render",
                            "--project", str(base)],
                           capture_output=True, text=True, timeout=900, cwd=base)
        rendered = sorted(base.rglob("*.mp4"))
        if r.returncode == 0 and rendered:
            clips: list[Path] = []
            for i, src in enumerate(rendered[:len(scenes)]):
                dst = Path(job_dir) / "clips" / f"auto-scene-{i + 1:02d}.mp4"
                dst.write_bytes(src.read_bytes())
                clips.append(dst)
            if clips:
                return clips, f"motion-canvas rendered {len(clips)} scene clips"
    except Exception as e:  # noqa: BLE001
        return [], f"motion-canvas render failed ({e}) — no text-card fallback."
    return [], ("motion-canvas render failed — no clips produced, no "
                "text-card fallback. Fix the Motion Canvas project or pick "
                "the stills backend.")


def render_manim(job_dir: Path, scenes: list[dict],
                 options: JobOptions) -> tuple[list[Path], str]:
    """Try Manim (720p). NO fallback to text cards on any failure."""
    if shutil.which("manim") is None:
        return [], ("manim not installed — install it (`pip install manim`), "
                    "or pick the stills backend. No text-card fallback.")
    base = Path(job_dir) / "animation" / "manim"
    base.mkdir(parents=True, exist_ok=True)
    (base / "scene.py").write_text(
        "from manim import *\n\n" + "\n".join(
            f"class Scene{i + 1:02d}(Scene):\n"
            f"    def construct(self):\n"
            f"        # Scene {i + 1}: {str(scene.get('narration', ''))[:60]}\n"
            f"        self.wait({scene['duration']})\n"
            for i, scene in enumerate(scenes)), encoding="utf-8")
    try:
        r = subprocess.run(["manim", "render", "-qm", "--format=mp4",
                            "scene.py"] + [f"Scene{i + 1:02d}" for i in range(len(scenes))],
                           capture_output=True, text=True, timeout=1800, cwd=base)
        rendered = sorted(base.rglob("*.mp4"))
        if r.returncode == 0 and rendered:
            clips: list[Path] = []
            for i, src in enumerate(rendered[:len(scenes)]):
                dst = Path(job_dir) / "clips" / f"auto-scene-{i + 1:02d}.mp4"
                dst.write_bytes(src.read_bytes())
                clips.append(dst)
            if clips:
                return clips, f"manim rendered {len(clips)} scene clips (720p)"
    except Exception as e:  # noqa: BLE001
        return [], f"manim render failed ({e}) — no text-card fallback."
    return [], ("manim render failed — no clips produced, no text-card "
                "fallback. Fix the Manim project or pick the stills backend.")


def make_thumbnail(job_dir: Path, topic: str, angle: dict,
                   options: JobOptions) -> Path | None:
    """Thumbnail = a real still, centre-cropped, NO text added.

    Uses the middle scene's still (usually the most representative
    moment); falls back to scene 1. Returns None when no real still
    exists yet — a coloured card with the topic written on it is NOT
    a thumbnail. The 2-4 overlay words go on in CapCut only
    (see prompts/thumbnail.md).
    """
    from .stills import find_still, is_real_image
    job_dir = Path(job_dir)
    try:
        from PIL import Image  # type: ignore
    except ImportError:
        return None
    # Prefer the middle scene, then scene 1, then any real still.
    candidates = []
    stills_dir = job_dir / "stills"
    if stills_dir.exists():
        candidates = sorted(p for p in stills_dir.glob("scene-*.*")
                            if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp"))
    if not candidates:
        return None
    pick = candidates[len(candidates) // 2] if len(candidates) > 1 else candidates[0]
    if not is_real_image(pick):
        return None
    try:
        with Image.open(pick) as img:
            img = img.convert("RGB")
            w, h = options.width, options.height
            # Centre-crop (cover) to the target aspect, no text, no banner.
            target = w / h
            iw, ih = img.size
            if iw / ih > target:
                nw = int(ih * target)
                x0 = (iw - nw) // 2
                img = img.crop((x0, 0, x0 + nw, ih))
            else:
                nh = int(iw / target)
                y0 = (ih - nh) // 2
                img = img.crop((0, y0, iw, y0 + nh))
            img = img.resize((w, h))
            out = job_dir / "thumbnail.jpg"
            img.save(out, quality=90)
            return out
    except Exception:
        return None


def render_visuals(job_dir: Path, scenes: list[dict], options: JobOptions,
                   angle: dict | None = None,
                   ) -> tuple[list[Path], str, str]:
    """Return (scene clips, backend_actually_used, log line)."""
    want = options.video_backend
    if want == "code":  # old jobs: "code" was the deleted card backend
        want = "stills"
    if want == "flow-manual":
        return [], "", ("flow-manual chosen: Flow has no public API, so visuals "
                        "cannot be auto-rendered. Paste prompts/flow-prompts.txt "
                        "into Flow by hand, then run assemble.")
    if want in ("auto", "stills"):
        clips, log = render_stills(job_dir, scenes, options, angle)
        return clips, "stills", log
    if want == "motion-canvas":
        clips, log = render_motion_canvas(job_dir, scenes, options)
        return clips, "motion-canvas" if clips else "", log
    if want == "manim":
        clips, log = render_manim(job_dir, scenes, options)
        return clips, "manim" if clips else "", log
    return [], "", f"Unknown video backend: {want!r} (pick stills, motion-canvas, manim or flow-manual)."
